function leg(person, taskIndex, beneficiary, complete = false) {
  const p =
    person === "you"
      ? { owner: "Jamie Davis", initials: "JD", color: "rose" }
      : people[person];
  return {
    name: p.owner,
    initials: p.initials,
    color: p.color,
    task: demoTasks[taskIndex].title,
    for: beneficiary,
    done: complete,
  };
}
function sample(id, status, a, b, timing) {
  return {
    id,
    origin: "sample",
    status,
    legs: [a, b],
    timing,
    criteria:
      "Both task owners review their deliverables against the agreed briefs.",
    activity: [
      { text: `Example scenario: ${status.toLowerCase()} exchange.`, at: null },
    ],
  };
}
